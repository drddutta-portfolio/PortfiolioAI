function text(value:unknown){return typeof value==="string"&&value.trim()?value.trim():null}
export function normalizeBenchmarkAlias(value:unknown){return text(value)?.toUpperCase().replace(/&/gu," AND ").replace(/[^A-Z0-9]+/gu," ").trim().replace(/\s+/gu," ")??""}
export function benchmarkDefinition(code:string){const row=P7_IC_BENCHMARK_REGISTRY.find(item=>item.code===code);if(!row)throw new Error("P7_IC_BENCHMARK_CODE_UNSUPPORTED");return row}
